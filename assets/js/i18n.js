import { IT2, EN2 } from './i18n2.js';
Object.assign(IT, IT2); Object.assign(EN, EN2);
const DICT = { it: IT, en: EN };
const KEY = 'altravi.team.lang';
const ROOT_KEY = 'altravi.lang';
let lang = 'en';
const subs = new Set();
(function init() {
  try {
    const ok = l => l === 'it' || l === 'en';
    let l = localStorage.getItem(KEY) || localStorage.getItem(ROOT_KEY);
    if (!ok(l)) {
      const p = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language]);
      l = 'en';
      for (const x of p) { const b = String(x || '').toLowerCase().split('-')[0]; if (ok(b)) { l = b; break; } }
    }
    lang = l;
  } catch { /* ignore */ }
})();
export const getLang = () => lang;
export const locale = () => (lang === 'it' ? 'it-IT' : 'en-GB');
export function setLang(l, persist = true) {
  if (l !== 'it' && l !== 'en') return;
  lang = l;
  document.documentElement.lang = l;
  if (persist) { try { localStorage.setItem(KEY, l); } catch { /* ignore */ } }
  subs.forEach(f => f(l));
}
export const onLang = f => { subs.add(f); return () => subs.delete(f); };
export function t(key, vars) {
  let s = DICT[lang][key];
  if (s == null) s = DICT.it[key];
  if (s == null) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : vars[k]));
  return s;
}
